function maskEmailForAdminDisplay(email) {
	const clean = String(email || "").trim();
	const atIdx = clean.indexOf("@");
	if (atIdx <= 1) return clean ? "***" : "Authenticated Session";
	const local = clean.slice(0, atIdx);
	const domain = clean.slice(atIdx + 1);
	return `${local.slice(0, Math.min(2, local.length))}***${local.length > 3 ? local.slice(-1) : ""}@${domain}`;
}
function maskPhoneForAdminDisplay(phone) {
	const clean = String(phone || "").trim();
	if (!clean) return "Hidden";
	if (clean.includes("*")) return clean;
	const digits = clean.replace(/\D/g, "");
	if (digits.length < 7) return "***";
	return `${clean.startsWith("+880") ? "+880" : digits.slice(0, 3)}****${digits.slice(-4)}`;
}
